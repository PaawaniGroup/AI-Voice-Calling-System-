"""Generate docs/ROUTES.md from the live FastAPI app (so the route list cannot drift from the code)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fastapi.routing import APIRoute, APIWebSocketRoute  # noqa: E402

from app.main import create_app  # noqa: E402
from config.settings import Settings  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
AUTH = {  # dependency name -> label
    "require_viewer": "viewer", "require_user": "operator", "require_admin": "admin", "require_platform": "platform",
}


def auth_of(route) -> str:
    names = {d.call.__name__ for d in route.dependant.dependencies if getattr(d, "call", None)}
    for k in ("require_platform", "require_admin", "require_user", "require_viewer"):
        if k in names:
            return AUTH[k]
    p = route.path
    if p.startswith("/v1/providers/"):
        return "Plivo V3 signature"
    if p in ("/v1/auth/login",):
        return "none (rate limited)"
    if p in ("/health/live", "/health/ready"):
        return "none"
    if p == "/metrics":
        return "metrics token / loopback"
    if p == "/v1/telephony/status":
        return "viewer (configurable)"
    return "?"


def main() -> None:
    app = create_app(Settings(_env_file=None, env="test", provider="mock", fs_enabled=False))
    rows = []
    for r in app.routes:
        if isinstance(r, APIRoute) and r.path not in ("/openapi.json", "/docs", "/docs/oauth2-redirect", "/redoc"):
            for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
                rows.append((r.path, m, auth_of(r), (r.endpoint.__doc__ or r.summary or "").strip().split("\n")[0][:110]))
        elif isinstance(r, APIWebSocketRoute):
            rows.append((r.path, "WS", "first-message JWT (operator)", "media WebSocket (see docs/AI_MEDIA_ADAPTER.md)"))
    rows.sort()
    out = ["# Routes (generated)", "", "_Generated by `python scripts/gen_routes_doc.py` from the running app. Roles: viewer < operator < admin; platform = cross-tenant._", "",
           f"**{len(rows)} routes**", "", "| Method | Path | Auth | Notes |", "|---|---|---|---|"]
    out += [f"| {m} | `{p}` | {a} | {n} |" for p, m, a, n in rows]
    out += ["", "Also: `/dashboard/` (static console), `/docs` and `/openapi.json` when `MME_TEL_DOCS_ENABLED=true`.", ""]
    (ROOT / "docs" / "ROUTES.md").write_text("\n".join(out), encoding="utf-8")
    print(len(rows), "routes")


if __name__ == "__main__":
    main()
