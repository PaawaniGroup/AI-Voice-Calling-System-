"""Generate docs/CONFIGURATION_REFERENCE.md, .env.example and docs/CONFIGURATION_COMPLETENESS.md from config/settings.py.

The settings model is the single source of truth, so documentation cannot drift from the code.
Run: python scripts/gen_config_docs.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pydantic import SecretStr  # noqa: E402
from pydantic_core import PydanticUndefined  # noqa: E402

from config.settings import Settings  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
# (prefix of field name) -> (component, category)
CATS = [
    ("app_|env|bind_|workers|request_timeout|shutdown|max_body|trusted|api_prefix|docs_|cors", "API/runtime"),
    ("mongo_|retention_", "Database"),
    ("esl_|fs_|reconcile_|initiating", "FreeSWITCH/ESL"),
    ("rtp_|ring_|answer_|transfer_|max_call|webrtc", "SIP/RTP/WebRTC"),
    ("provider|plivo_|webhook_public|real_calls|estimate", "Provider"),
    ("max_active|max_queued|queue_|max_initiation|dispatch_|default_", "Call control/queue"),
    ("jwt_|role_|rate_limit|metrics_|status_requires|webhook_signing", "Auth/security"),
    ("recording_|storage_|s3_", "Recording/storage"),
    ("webhooks_|webhook_", "Outbound webhooks"),
    ("log_|tracing|ready_", "Observability"),
    ("ai_", "AI (Phase 3, must stay off)"),
]


def category(name: str) -> str:
    import re
    for pat, cat in CATS:
        if re.match(f"^({pat})", name):
            return cat
    return "Other"


def rows():
    out = []
    for name, f in Settings.model_fields.items():
        extra = f.json_schema_extra or {}
        default = f.default
        secret = isinstance(default, SecretStr)
        required = default is PydanticUndefined
        constraints = []
        for m in f.metadata:
            for k in ("ge", "gt", "le", "lt", "min_length", "max_length"):
                if hasattr(m, k) and getattr(m, k) is not None:
                    constraints.append(f"{k}={getattr(m, k)}")
        ann = str(f.annotation).replace("typing.", "").replace("<class '", "").replace("'>", "")
        if "Literal" in ann:
            constraints.append("one of " + ann[ann.index("[") + 1:-1])
            ann = "enum"
        shown = "(secret)" if secret else repr(default)
        out.append(dict(
            env="MME_TEL_" + name.upper(), cat=category(name), type=ann, required=required,
            secret=secret, default=shown, unset_secret=secret and not default.get_secret_value(),
            dev_only=bool(extra.get("dev_only")), restart=bool(extra.get("restart", True)),
            constraints=", ".join(constraints) or "-", desc=f.description or ""))
    return out


def main():
    R = rows()
    # Reference
    lines = ["# Configuration reference", "",
             "_Generated by `python scripts/gen_config_docs.py` from `config/settings.py` (authoritative). Do not edit by hand._", "",
             "Precedence: process environment > `.env` (development only) > defaults. Secrets come only from the environment or a secret manager.",
             "Non-secret policy: `config/telephony.yaml`. Provider structure: `config/provider.example.yaml`.", "",
             "**Failure behaviour (all parameters):** a type/range violation fails startup with a sanitized error naming the variable (never its value). "
             "Cross-field rules are in `Settings.problems()`; production-like environments additionally require secrets and forbid the mock provider. "
             "**Environment column:** `all` unless noted; *dev-only* values trigger a warning (or an error in staging/production when unsafe).", ""]
    cur = None
    for r in sorted(R, key=lambda x: (x["cat"], x["env"])):
        if r["cat"] != cur:
            cur = r["cat"]
            lines += [f"## {cur}", "", "| Variable | Type | Required | Default | Secret | Valid range / values | Restart | Env | Purpose |", "|---|---|---|---|---|---|---|---|---|"]
        req = "yes" if r["required"] else ("prod" if r["secret"] else "no")
        env = "dev/test only" if r["dev_only"] else "all"
        lines.append(f"| `{r['env']}` | {r['type']} | {req} | {r['default'] if r['default'] != chr(39)*2 else '`\"\"`'} | {'**yes**' if r['secret'] else 'no'} | {r['constraints']} | {'yes' if r['restart'] else 'no'} | {env} | {r['desc']} |")
    lines.append("")
    lines += ["## Not in settings.py", "",
              "* `MME_TEL_TEST_MONGO_URI` (tests only): MongoDB used by `pytest`; default `mongodb://127.0.0.1:27117` (see `scripts/dev_mongo.sh`).",
              "* `MME_VENV` (dev helper `scripts/run.sh`): path of the virtualenv.", "",
              "`prod` in *Required* = a secret required when `MME_TEL_ENV` is `staging`/`production`.", ""]
    (ROOT / "docs" / "CONFIGURATION_REFERENCE.md").write_text("\n".join(lines), encoding="utf-8")

    # .env.example
    env = ["# MME_TELEPHONY environment template. Copy to .env (never commit .env). All values are placeholders.",
           "# Full reference: docs/CONFIGURATION_REFERENCE.md", ""]
    cur = None
    for r in sorted(R, key=lambda x: (x["cat"], x["env"])):
        if r["cat"] != cur:
            cur = r["cat"]
            env += ["", f"# ---- {cur} ----"]
        env.append(f"# {r['desc']}" + (" [DEV ONLY]" if r["dev_only"] else ""))
        if r["secret"]:
            env.append(f"{r['env']}=")
        else:
            d = r["default"]
            val = d.strip("'") if d.startswith("'") else d
            env.append(f"{r['env']}={'' if val in (chr(39)*2, '') else val}")
    (ROOT / ".env.example").write_text("\n".join(env) + "\n", encoding="utf-8")

    # Completeness
    total = len(R)
    req = [r for r in R if r["required"]]
    secrets = [r for r in R if r["secret"]]
    opt = total - len(req)
    verify = [r["env"] for r in R if r["env"] in (
        "MME_TEL_PROVIDER_MAX_CONCURRENT", "MME_TEL_PROVIDER_MAX_CPS", "MME_TEL_WEBHOOK_PUBLIC_BASE_URL", "MME_TEL_PLIVO_AUTH_ID",
        "MME_TEL_PLIVO_AUTH_TOKEN", "MME_TEL_FS_GATEWAY", "MME_TEL_RTP_PORT_START", "MME_TEL_RTP_PORT_END", "MME_TEL_ESTIMATE_RATE_PER_MIN",
        "MME_TEL_DEFAULT_ALLOWED_COUNTRIES", "MME_TEL_S3_BUCKET", "MME_TEL_S3_REGION")]
    comp = f"""# Configuration completeness

_Generated by `python scripts/gen_config_docs.py`; the manual sections below are maintained by hand._

| Metric | Value |
|---|---|
| Total parameters (`config/settings.py`) | **{total}** |
| Required in every environment (no default) | **{len(req)}** |
| Required only in staging/production (validated by `Settings.problems()`) | **4**: `MME_TEL_MONGO_URI`, `MME_TEL_JWT_SECRET`, `MME_TEL_WEBHOOK_SIGNING_MASTER`, `MME_TEL_ESL_PASSWORD` (when FreeSWITCH enabled) |
| Optional (safe default exists) | **{opt}** |
| Secret parameters (never logged; empty default; validated in staging/production) | **{len(secrets)}**: {', '.join('`'+r['env']+'`' for r in secrets)} |
| Development-only parameters | {', '.join('`'+r['env']+'`' for r in R if r['dev_only'])} |

## Parameters needing operator input before production
`MME_TEL_ENV=production`, `MME_TEL_MONGO_URI`, `MME_TEL_JWT_SECRET`, `MME_TEL_WEBHOOK_SIGNING_MASTER`, `MME_TEL_ESL_PASSWORD`,
`MME_TEL_BIND_HOST`/TLS proxy, and (provider path) `MME_TEL_FS_GATEWAY` or the Plivo credentials + `MME_TEL_WEBHOOK_PUBLIC_BASE_URL`.

## Parameters requiring provider / infrastructure verification (defaults are placeholders, NOT verified facts)
{chr(10).join('* `'+v+'`' for v in verify)}

## Parameters with unverified defaults
`MME_TEL_PROVIDER_MAX_CONCURRENT=10` and `MME_TEL_PROVIDER_MAX_CPS=1` are conservative guesses, **not** the Plivo account limits.
`MME_TEL_DEFAULT_DENY_PREFIXES` is a starting list of Indian premium/telemarketing prefixes and needs compliance review.

## Verified in this repository (see docs/TEST_REPORT.md)
* Settings validation, cross-field rules and production-secret enforcement: `tests/unit/test_configuration.py`.
* `scripts/validate_config.py` exit codes (ok / warnings / errors): same test file.
* ESL host/port/password work against the local FreeSWITCH 1.11.4-dev: `tests/integration/test_freeswitch.py`.

## Secret-management status
No secret is stored in the repository. `.env` is git-ignored; `.env.example` lists placeholders only. Production secrets must come from
the host secret manager into a root-owned 0600 environment file (see docs/DEPLOYMENT.md). Rotation procedure: docs/SECURITY.md.

## Development / test / production differences
| Setting | development | test | production |
|---|---|---|---|
| provider `mock` | allowed | allowed | **rejected** |
| docs endpoints | on | on | warn if on |
| webhook http/private destinations | allowed (warn) | allowed | **rejected** |
| JWT secret / signing master / ESL password | warn if empty | provided by fixtures | **required, >=32 chars** |
| real PSTN calls | off (`MME_TEL_REAL_CALLS_ENABLED`) | off | explicit opt-in |

## Features disabled when configuration is incomplete
* Recording: off unless `RECORDING_ENABLED` + consent mode + storage backend (+ tenant policy `recording=on`).
* PSTN origination: refused unless `REAL_CALLS_ENABLED=true`.
* Calling per tenant: refused until a tenant policy with `enabled=true` and approved caller IDs exists.
* Browser calling (WebRTC) and AI: not implemented / forced off (startup rejects `WEBRTC_ENABLED`, `AI_ENABLED`).

## Startup validation results
Run `python scripts/validate_config.py`; latest recorded output is in docs/TEST_REPORT.md.
"""
    (ROOT / "docs" / "CONFIGURATION_COMPLETENESS.md").write_text(comp, encoding="utf-8")
    print(f"{total} parameters, {len(req)} required, {len(secrets)} secret")


if __name__ == "__main__":
    main()
